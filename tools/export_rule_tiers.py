"""
Write docs/RULE_TIERS.md: the rule -> tier/subtype table for the paper side (Pass-through P1b),
generated from policy.RULE_TIERS and the rule patterns so it can never drift from the code.

    python tools/export_rule_tiers.py          # rewrite docs/RULE_TIERS.md
    python tools/export_rule_tiers.py --check  # exit 1 if the file is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from hallucination_pipeline import policy as POL  # noqa: E402
from hallucination_pipeline.detection import patterns as P  # noqa: E402
from hallucination_pipeline.detection.version import RULES_VERSION, rules_patterns_sha256  # noqa: E402

OUT = REPO_ROOT / "docs" / "RULE_TIERS.md"

# (rule key, layer, how it fires) in the order the sentence engine checks them
LAYERS = (
    [(d, "1 hard pattern", p.pattern) for p, _, d in P.FACTUAL_PATTERNS + P.REASONING_PATTERNS + P.CERTAINTY_PATTERNS]
    + [(POL.PORT_MISMATCH, "2 port mismatch", r"\bport\s+(\d+)\b with the number absent from the evidence")]
    + [(POL.PROTOCOL_INJECTION, "3 protocol injection",
        "protocol name (" + P.PROTOCOL_NAME_RE.pattern + ") whose well-known port is absent from the evidence, "
        "or which has no well-known port")]
    + [(d, "4 external knowledge", p.pattern) for p, d in P.EXTERNAL_KNOWLEDGE_PATTERNS]
    + [(POL.SOFT_CERTAINTY, "5 soft certainty", P.SOFT_CERTAINTY_RE.pattern)]
)


def render() -> str:
    stamp = POL.policy_stamp()
    yes = lambda tier, pol: "yes" if POL.counts_as_hallucination(tier, pol) else "no"
    lines = [
        "# Rule -> tier table (Pass-through P1b)",
        "",
        "Generated by `tools/export_rule_tiers.py` from `hallucination_pipeline/policy.py`. Do not edit by hand.",
        f"Rules version {RULES_VERSION} (patterns SHA-256 `{rules_patterns_sha256()[:12]}...`); "
        f"policy version {stamp['policy_version']} (tier map SHA-256 `{stamp['tier_map_sha256'][:12]}...`).",
        "",
        "Tier 1 = unsupported specifics; Tier 2 = external knowledge (DECISIONS D3). **strict** counts Tier 1 + 2, "
        "**lenient** counts Tier 1 only. Layers are checked in the order shown; at sentence level the first rule "
        "that fires decides, so a Tier 2 verdict means no Tier 1 rule fired. Soft certainty never decides on its "
        "own: it sends the sentence (or explanation) to the LLM judge. At explanation level, layers 1-3 are the "
        "old Phase 2 rules (C0, C2); layer 4 is added for C1 and C3.",
        "",
        "| # | Layer | Rule | Engine type | Tier | Subtype | strict | lenient |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, (key, layer, _) in enumerate(LAYERS, start=1):
        t = POL.RULE_TIERS[key]
        counted = ("escalate", "escalate") if key == POL.SOFT_CERTAINTY else (yes(t.tier, "strict"), yes(t.tier, "lenient"))
        lines.append(f"| {i} | {layer} | {key} | {t.type} | {t.tier} | {t.subtype} | {counted[0]} | {counted[1]} |")
    lines += ["", "## What each rule matches", ""]
    for i, (key, _, how) in enumerate(LAYERS, start=1):
        lines += [f"**{i}. {key}**", "", "```", how, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = render()
    if ap.parse_args().check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        print("up to date" if current == text else f"{OUT} is out of date: run tools/export_rule_tiers.py")
        return 0 if current == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
