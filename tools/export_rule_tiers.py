"""
Write docs/RULE_TIERS.md (rule -> tier/subtype table) and docs/SUBTYPES.md (the exact subtype
vocabulary) for the paper side, generated from policy.py so they can never drift from the code.

    python tools/export_rule_tiers.py          # rewrite both files
    python tools/export_rule_tiers.py --check  # exit 1 if either file is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from hallucination_pipeline import policy as POL  # noqa: E402
from hallucination_pipeline.detection import patterns as P  # noqa: E402
from hallucination_pipeline.detection.version import RULES_VERSION, rules_patterns_sha256  # noqa: E402

RULE_TIERS_MD = REPO_ROOT / "docs" / "RULE_TIERS.md"
SUBTYPES_MD = REPO_ROOT / "docs" / "SUBTYPES.md"

# (rule key, layer, how it fires) in the order the sentence engine checks them
LAYERS = (
    [(d, "1 hard pattern", p.pattern) for p, _, d in P.FACTUAL_PATTERNS + P.REASONING_PATTERNS + P.CERTAINTY_PATTERNS]
    + [(POL.PORT_MISMATCH, "2 port mismatch", r"\bport\s+(\d+)\b with the number absent from the evidence")]
    + [(POL.PROTOCOL_INJECTION, "3 protocol injection",
        "protocol name (" + P.PROTOCOL_NAME_RE.pattern + ") whose well-known port is absent from the evidence, "
        "or which has no well-known port")]
    + [(d, "4 external knowledge", p.pattern) for p, d in P.EXTERNAL_KNOWLEDGE_PATTERNS]
    + [(POL.UNIT_WRONG, "5 duration check (D19)",
        "a stated duration " + POL.DURATION_CLAIM_RE.pattern + " that differs by more than "
        f"{POL.DURATION_TOLERANCE:.0%} from Flow Duration / 1,000,000 seconds (and is not that value rounded to "
        "the stated decimals). A Tier 2 `unit` hit in such a sentence becomes `unit_wrong`.")]
    + [(POL.SOFT_CERTAINTY, "6 soft certainty", P.SOFT_CERTAINTY_RE.pattern)]
)


def _header(title: str) -> list[str]:
    stamp = POL.policy_stamp()
    return [f"# {title}", "",
            "Generated by `tools/export_rule_tiers.py` from `hallucination_pipeline/policy.py`. Do not edit by hand.",
            f"Rules version {RULES_VERSION} (patterns SHA-256 `{rules_patterns_sha256()[:12]}...`); "
            f"policy version {stamp['policy_version']} (SHA-256 `{stamp['tier_map_sha256'][:12]}...`).", ""]


def render_rule_tiers() -> str:
    yes = lambda tier, pol: "yes" if POL.counts_as_hallucination(tier, pol) else "no"
    lines = _header("Rule -> tier table") + [
        "Tier 1 = unsupported specifics; Tier 2 = external knowledge (D3). **strict** counts Tier 1 + 2, "
        "**lenient** counts Tier 1 only. Layers are listed in the order the sentence engine checks them. Every "
        "matched rule is kept (D18); the primary one is the first Tier 1 hit in this order, else the first counted "
        "hit. Soft certainty never decides on its own: it sends the item to the LLM judge. At explanation level, "
        "layers 1-3 are the old Phase 2 rules (C0, C2); layers 4 and 5 are added for C1 and C3. Every hit carries "
        "`hedged` (D17, lexicon below), which never changes its tier.",
        "",
        "| # | Layer | Rule | Engine type | Tier | Subtype | strict | lenient |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, (key, layer, _) in enumerate(LAYERS, start=1):
        t = POL.RULE_TIERS[key]
        counted = ("escalate", "escalate") if key == POL.SOFT_CERTAINTY else (yes(t.tier, "strict"), yes(t.tier, "lenient"))
        lines.append(f"| {i} | {layer} | {key} | {t.type} | {t.tier} | {t.subtype} | {counted[0]} | {counted[1]} |")
    lines += ["", "## Hedging lexicon (D17, frozen)", "",
              ", ".join(f"`{w}`" for w in POL.HEDGE_LEXICON) + " (whole words, case-insensitive).", "",
              "## What each rule matches", ""]
    for i, (key, _, how) in enumerate(LAYERS, start=1):
        lines += [f"**{i}. {key}**", "", "```", how, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_subtypes() -> str:
    lines = _header("Subtype vocabulary") + [
        "The exact names to use in v2 prompts, v2 judge replies and the annotation guide. A v2 judge reply whose "
        "`subtype` is not in the first table, or whose `tier` does not match it, is recorded with a "
        "`reply_problems` entry.",
        "",
        "Reply fields. Explanation level: `contains_hallucination`, `confidence`, `tier` (1, 2 or null), "
        "`subtype`, `reason`. Sentence level: `label` (`hallucinated` or `grounded`), `confidence`, `tier`, "
        "`subtype`, `reason`. Use `null` for tier and subtype when there is no hallucination.",
        "",
        "| Subtype | Tier | Type | Meaning |",
        "|---|---|---|---|",
    ]
    for name, s in POL.SUBTYPES.items():
        if s.label:
            lines.append(f"| `{name}` | {s.tier} | {s.type} | {s.meaning} |")
    lines += ["", "Rule-internal markers (never a label, never a valid reply subtype):", "",
              "| Marker | Meaning |", "|---|---|"]
    for name, s in POL.SUBTYPES.items():
        if not s.label:
            lines.append(f"| `{name}` | {s.meaning} |")
    lines += ["", "Placeholders in the v2 templates: "
              + "; ".join(f"`{n}`: " + ", ".join("`{" + p + "}`" for p in sorted(ph))
                          for n, ph in POL.PROMPT_PLACEHOLDERS.items())
              + ". Literal JSON braces are written `{{` and `}}`."]
    return "\n".join(lines).rstrip() + "\n"


def documents() -> dict[Path, str]:
    return {RULE_TIERS_MD: render_rule_tiers(), SUBTYPES_MD: render_subtypes()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    check = ap.parse_args().check
    stale = []
    for path, text in documents().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"Wrote {path}")
    if stale:
        print("Out of date: " + ", ".join(str(p) for p in stale) + " -> run tools/export_rule_tiers.py")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
