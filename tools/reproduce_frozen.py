"""
Reproduce the Paper 1 numbers from the frozen artifacts, and test the rebuild
against them.

Usage:
    python tools/reproduce_frozen.py --frozen-dir /path/to/frozen [--out REPORT.md]

The frozen directory is flat and should contain: alerts.json, llm_explanations.json,
phase2_detection.json, phase3_predictions.json, sentence_gold_labels.json,
hallucination_masks.json, corrected_explanations.json.

No API key is used: everything here is deterministic. LLM-dependent figures
(for example the LLM re-check effectiveness) cannot be recomputed from these files
and are reported as "not checkable" rather than guessed.
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sklearn.metrics import cohen_kappa_score, confusion_matrix

from hallucination_pipeline.detection import (
    rule_based_detect_explanation, rule_classify_sentence, split_sentences)
from hallucination_pipeline.evaluation import gold_to_int
from hallucination_pipeline.impact_analysis import aggregate, analyze_alerts
from hallucination_pipeline.unlearning import build_masks

# What the Paper 1 draft reports.
PAPER = {
    "t1": dict(gold=183, pred=97, tp=96, fp=1, fn=87, p=0.9897, r=0.5246, f1=0.6857),
    "t2": dict(n=989, gold=90, pred=132, tp=69, fp=63, fn=21, p=0.4964, r=0.7667, f1=0.6026),
    "t3": {"external_knowledge_unit": 29, "external_knowledge_port": 28, "invalid_knowledge": 15,
           "external_knowledge_baseline": 9, "external_knowledge_encryption": 8, "overconfidence": 1},
    "t4": dict(before_all=721, after_all=607, red_all=15.8, before_mod=215, after_mod=101, red_mod=53.0, modified=88),
}


def prf(y, p):
    tn, fp, fn, tp = confusion_matrix(y, p, labels=[0, 1]).ravel()
    pr = tp / (tp + fp) if tp + fp else 0.0
    rc = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * pr * rc / (pr + rc) if pr + rc else 0.0
    return dict(tp=int(tp), fp=int(fp), fn=int(fn), p=round(pr, 4), r=round(rc, 4), f1=round(f1, 4))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frozen-dir", type=Path, required=True)
    ap.add_argument("--out", type=Path)
    d = ap.parse_args().frozen_dir
    L = lambda n: json.loads((d / n).read_text())
    alerts, expl = L("alerts.json"), L("llm_explanations.json")
    p2, p3, g3 = L("phase2_detection.json"), L("phase3_predictions.json"), L("sentence_gold_labels.json")
    masks, corrected = L("hallucination_masks.json"), L("corrected_explanations.json")
    amap = {a["alert_id"]: a for a in alerts}
    toks = lambda aid: {str(t).lower() for t in amap[aid]["evidence_tokens"]}
    out: list[str] = []
    w = out.append

    w("# Paper 1 reproduction report\n")
    w("Generated by `tools/reproduce_frozen.py` from the frozen artifacts. Deterministic; no API calls.\n")

    # ---- A. is the rebuild faithful to the frozen run? -------------------
    w("## A. Does the rebuilt code reproduce the frozen run?\n")
    r955 = [r for r in p3 if str(r["detection_method"]).startswith("rule")]
    same = sum(1 for r in r955 if (lambda o: o["label"] == r["predicted_label"] and o["hallucination_type"] == r["hallucination_type"]
                                   and o["reason"] == r["reason"])(rule_classify_sentence(r["sentence_text"], toks(r["alert_id"]))))
    w(f"- Phase 3 (955-sentence file), rule-decided sentences: **{same}/{len(r955)}** identical label, type and reason text.")
    r989 = [r for r in g3 if str(r["detection_method"]).startswith("rule")]
    lab = sum(1 for r in r989 if rule_classify_sentence(r["sentence_text"], toks(r["alert_id"]))["label"] == r["predicted_label"])
    w(f"- Phase 3 (989-sentence file used for Table II), rule-decided: **{lab}/{len(r989)}** same label; reason text never identical "
      f"-> produced by an older rule version.")
    rr = [x for x in p2 if x["detection_method"] == "rule"]
    ok = sum(1 for x in rr if (rule_based_detect_explanation(next(e for e in expl if e["alert_id"] == x["alert_id"])["explanation"],
                                                             amap[x["alert_id"]]["evidence_tokens"])["triggered"] is True) == x["contains_hallucination"])
    w(f"- Phase 2 frozen file, rule-decided explanations: **{ok}/{len(rr)}** agree.")
    mm = build_masks(p3)
    fz = {(m["alert_id"], m["sentence_id"]): (m["action"], m["hallucination_type"]) for m in masks}
    gold_ok = sum(1 for m in mm if fz[(m["alert_id"], m["sentence_id"])] == (m["action"], m["hallucination_type"]))
    pm = build_masks([{**r, "gold_label": None} for r in p3])
    pred_ok = sum(1 for m in pm if fz[(m["alert_id"], m["sentence_id"])] == (m["action"], m["hallucination_type"]))
    w(f"- Phase 4 masks: rebuilt from **gold labels** match **{gold_ok}/{len(mm)}**; rebuilt from predictions only match {pred_ok}/{len(pm)}. "
      f"-> **Phase 4 was driven by gold labels** (QUALIFY: {sum(m['action']=='QUALIFY' for m in mm)} from gold vs {sum(m['action']=='QUALIFY' for m in pm)} from predictions).\n")

    # ---- B. paper tables vs recomputed -----------------------------------
    w("## B. Paper tables versus the frozen data\n")
    w("| Item | Paper | Recomputed | Verdict |\n|---|---|---|---|")
    y = [gold_to_int(x["gold_label"]) for x in p2]; pr_ = [1 if x["contains_hallucination"] else 0 for x in p2]
    t1 = prf(y, pr_)
    w(f"| Table I gold / predicted | {PAPER['t1']['gold']} / {PAPER['t1']['pred']} | {sum(y)} / {sum(pr_)} | does not reproduce |")
    w(f"| Table I precision / recall / F1 | {PAPER['t1']['p']} / {PAPER['t1']['r']} / {PAPER['t1']['f1']} | {t1['p']} / {t1['r']} / {t1['f1']} | does not reproduce |")
    y3 = [gold_to_int(x["gold_label"]) for x in g3]; p3_ = [1 if x["predicted_label"] == "hallucinated" else 0 for x in g3]
    t2 = prf(y3, p3_)
    w(f"| Table II precision / recall / F1 | {PAPER['t2']['p']} / {PAPER['t2']['r']} / {PAPER['t2']['f1']} | {t2['p']} / {t2['r']} / {t2['f1']} | **reproduces** |")
    w(f"| Table II predicted / FP | {PAPER['t2']['pred']} / {PAPER['t2']['fp']} | {sum(p3_)} / {t2['fp']} | **counts are wrong in the paper** |")
    conf = collections.Counter(x["hallucination_type"] for x in g3 if x["gold_label"] == "hallucinated")
    w(f"| Table III type distribution | {sum(PAPER['t3'].values())} sentences | {sum(conf.values())} sentences | {'**reproduces**' if dict(conf) == PAPER['t3'] else 'differs'} |")
    res, pairs, stats = analyze_alerts(alerts, corrected, p3, masks)
    imp = aggregate(res, pairs, stats, 0, 0)["hallucination_reduction"]
    w(f"| Table IV all alerts (before -> after) | 721 -> 607 (15.8%) | {imp['overall']['before']} -> {imp['overall']['after']} ({imp['overall']['reduction_pct']}%) | **reproduces** |")
    w(f"| Table IV modified alerts | 88: 215 -> 101 (53.0%) | {sum(r['modified'] for r in res)}: {imp['modified_alerts_only']['before']} -> {imp['modified_alerts_only']['after']} ({imp['modified_alerts_only']['reduction_pct']}%) | **reproduces** |")
    w("| Table V (LLM re-check 22%, 'paper rules' 83.3%) | see paper | needs unlearning_impact.json and the 'paper rules' evaluator | not checkable |\n")

    # ---- C. what the data additionally shows -----------------------------
    w("## C. Further findings from the frozen data\n")
    ac = collections.Counter(a["alert_type"] for a in alerts)
    w(f"- **Dataset composition:** {dict(ac)}. `Normal Traffic` is {100*ac['Normal Traffic']/len(alerts):.0f}% of the 400 'attack-class' alerts "
      f"(the loader excluded the label `BENIGN`, but this dataset version names benign flows `Normal Traffic`). "
      f"Only {len(alerts)-ac['Normal Traffic']} are attacks; the paper's named categories Heartbleed, Web Attack, Infiltration, Botnet and DoS Hulk/GoldenEye/Slowhttptest do not occur.")
    mod = [c for c in corrected if c["sentences_qualified"] or c["sentences_removed"]]
    w(f"- **Benign flows dominate what Phase 4 touched:** {sum(c['alert_type']=='Normal Traffic' for c in mod)} of {len(mod)} modified alerts ({100*sum(c['alert_type']=='Normal Traffic' for c in mod)/len(mod):.0f}%).")
    ref = {}
    n_hit = 0
    for e in expl:
        t = toks(e["alert_id"]); labs = [rule_classify_sentence(s, t) for s in split_sentences(e["explanation"])]
        ref[e["alert_id"]] = any(l["label"] == "hallucinated" for l in labs); n_hit += sum(l["label"] == "hallucinated" for l in labs)
    flagged = {x["alert_id"] for x in p2 if x["contains_hallucination"]}
    tp = sum(ref[a] for a in flagged); fn = sum(ref[a] for a in ref if a not in flagged)
    w(f"- **Coverage:** under the paper's own four-layer sentence rules, {sum(ref.values())}/{len(ref)} explanations contain a flagged sentence "
      f"({n_hit} flagged sentences = the paper's 721). Phase 2 forwards {len(flagged)}; against that reference its recall is {tp/(tp+fn):.3f}. "
      f"{sum(1 for r in res if not r['modified'])} alerts never reach Phase 4 and hold {sum(r['orig_hallucinated'] for r in res if not r['modified'])} of the {imp['overall']['before']} flagged sentences.")
    shared = sorted({(r["alert_id"], r["sentence_id"]) for r in g3} & {(r["alert_id"], r["sentence_id"]) for r in p3})
    gk = {(r["alert_id"], r["sentence_id"]): r["gold_label"] for r in g3}; pk = {(r["alert_id"], r["sentence_id"]): r["gold_label"] for r in p3}
    ka = cohen_kappa_score([gk[k] for k in shared], [pk[k] for k in shared])
    w(f"- **Gold labels are unstable:** two annotation rounds on the {len(shared)} shared sentences have Cohen's kappa = {ka:.3f} "
      f"({sum(gk[k]==pk[k] for k in shared)/len(shared):.1%} raw agreement). The 989-sentence round has {sum(v=='hallucinated' for v in gk.values())} positives; the 955-sentence round has {sum(v=='hallucinated' for v in pk.values())}.")
    num = lambda s: set(re.findall(r"\d+(?:\.\d+)?", s))
    new = [p for p in pairs if {n for n in num(p["corrected"]) if n not in num(p["evidence"]) | {str(t) for t in p["evidence_tokens"]} and n not in num(p["original"])}]
    still = sum(rule_classify_sentence(p["corrected"], {str(t).lower() for t in p["evidence_tokens"]})["label"] == "hallucinated" for p in pairs)
    w(f"- **Rewrite quality:** of {len(pairs)} QUALIFY rewrites, the rule engine flags {still}, but **{len(new)}** contain a figure found neither in the evidence nor in the original sentence "
      f"(e.g. a unit-converted '92 seconds' rewritten as '92000' for an evidence value of 92,190). The rules cannot detect this.")
    text = "\n".join(out)
    print(text)
    if (o := ap.parse_args().out):
        o.write_text(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
